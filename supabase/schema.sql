-- Run this script once in Supabase Dashboard -> SQL Editor

CREATE TABLE IF NOT EXISTS public.workshop_users (
  username TEXT PRIMARY KEY,
  role TEXT NOT NULL DEFAULT 'Staff',
  pin TEXT NOT NULL DEFAULT '1111',
  modules TEXT NOT NULL DEFAULT '',
  active BOOLEAN NOT NULL DEFAULT TRUE,
  units TEXT NOT NULL DEFAULT 'UL',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.workshop_settings (
  key TEXT PRIMARY KEY,
  settings JSONB NOT NULL DEFAULT '{}'::jsonb,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.daily_reports (
  report_key TEXT PRIMARY KEY,
  report_date TEXT NOT NULL,
  unit TEXT NOT NULL,
  data JSONB NOT NULL DEFAULT '{}'::jsonb,
  filled INTEGER NOT NULL DEFAULT 0,
  total INTEGER NOT NULL DEFAULT 0,
  submitted TEXT NOT NULL DEFAULT '',
  updated_by TEXT NOT NULL DEFAULT '',
  updated_at_text TEXT NOT NULL DEFAULT '',
  synced_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_daily_reports_date ON public.daily_reports (report_date, unit);

CREATE TABLE IF NOT EXISTS public.workshop_entries (
  id TEXT PRIMARY KEY,
  mod TEXT NOT NULL,
  entry_date TEXT NOT NULL,
  unit TEXT NOT NULL,
  store TEXT NOT NULL DEFAULT '',
  summary TEXT NOT NULL DEFAULT '',
  garment TEXT NOT NULL DEFAULT '',
  tag TEXT NOT NULL DEFAULT '',
  invoice_no TEXT NOT NULL DEFAULT '',
  worker_name TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT '',
  qty NUMERIC,
  points NUMERIC,
  remarks TEXT NOT NULL DEFAULT '',
  data JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_by TEXT NOT NULL DEFAULT '',
  entry_time TEXT NOT NULL DEFAULT '',
  stamp TEXT NOT NULL DEFAULT '',
  synced_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_workshop_entries_date ON public.workshop_entries (entry_date);
CREATE INDEX IF NOT EXISTS ix_workshop_entries_mod_date ON public.workshop_entries (mod, entry_date);
CREATE INDEX IF NOT EXISTS ix_workshop_entries_store ON public.workshop_entries (store);

CREATE TABLE IF NOT EXISTS public.workshop_lots (
  lot_key TEXT PRIMARY KEY,
  lot_date TEXT NOT NULL,
  unit TEXT NOT NULL,
  lot_type TEXT NOT NULL,
  cleared INTEGER NOT NULL DEFAULT 0,
  log JSONB NOT NULL DEFAULT '[]'::jsonb,
  updated_by TEXT NOT NULL DEFAULT '',
  updated_at_text TEXT NOT NULL DEFAULT '',
  synced_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_workshop_lots_date ON public.workshop_lots (lot_date, unit);

CREATE TABLE IF NOT EXISTS public.due_list (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  due_date TEXT NOT NULL DEFAULT '',
  barcode TEXT NOT NULL,
  store TEXT NOT NULL DEFAULT '',
  garment TEXT NOT NULL DEFAULT '',
  service TEXT NOT NULL DEFAULT '',
  unit TEXT NOT NULL DEFAULT '',
  synced_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_due_list_due_date ON public.due_list (due_date);
CREATE INDEX IF NOT EXISTS ix_due_list_barcode ON public.due_list (barcode);

CREATE TABLE IF NOT EXISTS public.workshop_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  logged_at TEXT NOT NULL,
  username TEXT NOT NULL DEFAULT '',
  action TEXT NOT NULL,
  detail TEXT NOT NULL DEFAULT '',
  synced_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_workshop_logs_logged_at ON public.workshop_logs (logged_at DESC);

CREATE TABLE IF NOT EXISTS public.workshop_kv (
  k TEXT PRIMARY KEY,
  v TEXT NOT NULL DEFAULT '',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.workshop_photos (
  id TEXT PRIMARY KEY,
  mime_type TEXT NOT NULL DEFAULT 'image/jpeg',
  data_base64 TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Enable Row Level Security and grant access for publishable/anon API key
ALTER TABLE public.workshop_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.workshop_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.daily_reports ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.workshop_entries ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.workshop_lots ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.due_list ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.workshop_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.workshop_kv ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.workshop_photos ENABLE ROW LEVEL SECURITY;

GRANT USAGE ON SCHEMA public TO anon, authenticated;
GRANT ALL ON ALL TABLES IN SCHEMA public TO anon, authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated;

DO $$
DECLARE
  tbl TEXT;
BEGIN
  FOREACH tbl IN ARRAY ARRAY[
    'workshop_users',
    'workshop_settings',
    'daily_reports',
    'workshop_entries',
    'workshop_lots',
    'due_list',
    'workshop_logs',
    'workshop_kv',
    'workshop_photos'
  ]
  LOOP
    EXECUTE format('DROP POLICY IF EXISTS "workshop_full_access" ON public.%I;', tbl);
    EXECUTE format('CREATE POLICY "workshop_full_access" ON public.%I FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);', tbl);
  END LOOP;
END $$;

NOTIFY pgrst, 'reload schema';
